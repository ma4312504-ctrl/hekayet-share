-- حكاية شارع: بداية قاعدة بيانات Supabase
-- شغّل هذا السكربت في SQL Editor بمشروع Supabase جديد.
-- أنشئ المستخدمين أولًا من Authentication، ثم أضف صفوفهم إلى user_profiles من لوحة SQL.
create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'editor' check (role in ('admin','editor'))
);

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  category text not null default 'المنيا ومراكزها',
  summary text not null,
  body text not null,
  image_url text,
  video_url text,
  author_id uuid references auth.users(id),
  author_name text not null default 'هيئة التحرير',
  status text not null default 'draft' check (status in ('draft','published')),
  featured boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_profiles enable row level security;
alter table public.articles enable row level security;

-- الملف الشخصي: المستخدم يقرأ صفه فقط؛ تعيين المدير/المحررين يدويًا من لوحة SQL الموثوقة.
create policy "profile read own" on public.user_profiles
for select to authenticated using (user_id = (select auth.uid()));

-- الزوار يرون الأخبار المنشورة فقط.
create policy "public read published" on public.articles
for select to anon, authenticated using (status = 'published');

-- المحررون/المديرون الموجودون في user_profiles يمكنهم إضافة/تعديل الأخبار.
create policy "staff insert articles" on public.articles
for insert to authenticated
with check (exists (select 1 from public.user_profiles p where p.user_id = (select auth.uid()) and p.role in ('admin','editor')));

create policy "staff update articles" on public.articles
for update to authenticated
using (exists (select 1 from public.user_profiles p where p.user_id = (select auth.uid()) and p.role in ('admin','editor')))
with check (exists (select 1 from public.user_profiles p where p.user_id = (select auth.uid()) and p.role in ('admin','editor')));

create policy "staff delete articles" on public.articles
for delete to authenticated
using (exists (select 1 from public.user_profiles p where p.user_id = (select auth.uid()) and p.role in ('admin','editor')));

